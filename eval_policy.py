r"""
eval_policy.py -- does a trained policy actually beat no policy at all?
RUN IN THE "voiceclone" ENV.

    python eval_policy.py --run designA_budget4h --checkpoint best.pt --pairs 20

analyze_run.py only reads the TRAINING reward, which is confounded: those
episodes were generated by a *stochastic* policy mid-training, so the number
mixes the policy's learned mean with its exploration noise. This script asks
the question that actually matters -- generate the same utterance with and
without the learned edit, and compare.

The paired design
-----------------
CosyVoice2 is stochastic twice over: the LLM samples speech tokens, and HiFT's
source-filter vocoder draws fresh excitation noise every call (measured
earlier in this repo: two calls on the identical mel tensor differ by 0.09
max abs). So a naive A/B differs by generation randomness AND the mel edit,
and with a per-episode reward sigma near 0.09 the randomness would swamp the
effect.

The fix: a deterministic policy consumes NO random numbers (sample() with
deterministic=True takes the mean and never calls randn). So seeding the same
value before each arm makes both arms draw the identical token sequence and
the identical vocoder noise -- leaving the mel edit as the only difference
between them. That turns an unpaired comparison with sigma ~= 0.09 into a
paired one whose noise is only what the edit itself causes.

Reported as a paired t-statistic over pairs, plus the per-detector breakdown,
because "softmin went up" can hide "one detector improved and another got
worse".
"""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

import numpy as np
import torch

sys.path.insert(0, str(Path(__file__).resolve().parent))

import cloners
import reward as reward_mod
from env_config import RESULTS_ROOT, VOICE_DATA_ROOT
from mel_policy import MelResidualPolicy, mel_edit_hook
from train_ppo_mel import DEFAULT_TEXTS, load_voice

RL_RUNS = RESULTS_ROOT / "rl_runs"


def paired_stats(diffs: np.ndarray) -> tuple[float, float, float]:
    """mean difference, its standard error, and the paired t statistic."""
    n = len(diffs)
    if n < 2:
        return float(diffs.mean()) if n else 0.0, float("nan"), float("nan")
    mean = float(diffs.mean())
    se = float(diffs.std(ddof=1) / np.sqrt(n))
    t = mean / se if se > 0 else float("inf") if mean != 0 else 0.0
    return mean, se, t


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--run", required=True, help="run dir name under rl_runs/")
    ap.add_argument("--checkpoint", default="best.pt", help="best.pt | latest.pt | iter_NNNN.pt")
    ap.add_argument("--pairs", type=int, default=20, help="paired comparisons to run")
    ap.add_argument("--voices", nargs="*", default=None, help="default: whatever the run trained on")
    ap.add_argument("--wer-max", type=float, default=0.15)
    ap.add_argument("--sim-min", type=float, default=0.70)
    ap.add_argument("--device", default=None)
    ap.add_argument("--seed", type=int, default=12345, help="base seed; pair i uses seed+i")
    ap.add_argument("--keep-wavs", action="store_true")
    args = ap.parse_args()

    run_dir = RL_RUNS / args.run
    ckpt_path = run_dir / args.checkpoint
    if not ckpt_path.is_file():
        print(f"no checkpoint at {ckpt_path}")
        return 1

    device = args.device or ("cuda" if torch.cuda.is_available() else "cpu")
    blob = torch.load(ckpt_path, map_location="cpu", weights_only=False)
    trained_args = blob.get("args", {})
    voices = args.voices or trained_args.get("voices") or ["riven"]

    print(f"checkpoint : {ckpt_path.name}  (iteration {blob.get('iteration')}, "
          f"saved {blob.get('saved_at')})")
    print(f"voices     : {voices}")
    print(f"pairs      : {args.pairs}   device: {device}\n")

    policy = MelResidualPolicy(
        max_delta=trained_args.get("max_delta", 0.6),
        min_log_std=trained_args.get("min_log_std", -3.0),
    ).to(device)
    policy.load_state_dict(blob["policy"])
    policy.eval()

    # how far from identity is this policy, in the mel's own units?
    with torch.no_grad():
        eff_sigma = policy.log_std.clamp(min=policy.min_log_std).exp().mean().item()
    print(f"policy log_std -> sigma {eff_sigma:.5f}"
          f"   (init was {np.exp(trained_args.get('init_log_std', -2.0)):.5f})\n")

    cosy = cloners.load_model("CosyVoice2", device=device)
    for v in voices:
        ref, prompt = load_voice(v)
        cloners.enroll(ref, "CosyVoice2", prompt_text=prompt, alias=v, device=device)

    eval_dir = run_dir / "eval"
    eval_dir.mkdir(parents=True, exist_ok=True)
    lag = reward_mod.LagrangianMultipliers()   # lambdas irrelevant here; constraints reported raw

    rows = []
    for i in range(args.pairs):
        voice = voices[i % len(voices)]
        text = DEFAULT_TEXTS[i % len(DEFAULT_TEXTS)]
        ref, _ = load_voice(voice)
        seed = args.seed + i

        # --- arm A: no policy ---
        torch.manual_seed(seed)
        if torch.cuda.is_available():
            torch.cuda.manual_seed_all(seed)
        base_wav = eval_dir / f"pair{i:03d}_{voice}_base.wav"
        cloners.generate(text, ref, model="CosyVoice2", out_path=base_wav, device=device)

        # --- arm B: deterministic policy, SAME seed ---
        # deterministic=True draws no random numbers, so the LLM's token
        # sampling and HiFT's noise replay identically -- the mel edit is the
        # only difference between the two arms.
        torch.manual_seed(seed)
        if torch.cuda.is_available():
            torch.cuda.manual_seed_all(seed)
        pol_wav = eval_dir / f"pair{i:03d}_{voice}_policy.wav"
        with mel_edit_hook(cosy.model, policy, deterministic=True, device=device) as rec:
            cloners.generate(text, ref, model="CosyVoice2", out_path=pol_wav, device=device)
        delta_mag = float(np.mean([d.abs().mean().item() for d in rec.deltas])) if rec.deltas else 0.0

        rows.append({"i": i, "voice": voice, "text": text, "seed": seed,
                     "base_wav": base_wav, "pol_wav": pol_wav,
                     "delta_abs_mean": delta_mag})
        print(f"  pair {i:2d}  {voice:<8} |delta| {delta_mag:.5f}")

    # --- score both arms; one detector subprocess for everything ---
    print("\nscoring all clips in one detector call...")
    all_wavs = [r["base_wav"] for r in rows] + [r["pol_wav"] for r in rows]
    det = reward_mod.score_detectors_batch(all_wavs)

    for r in rows:
        for arm, key in (("base", "base_wav"), ("pol", "pol_wav")):
            rw, info = reward_mod.compute_reward(
                r[key], load_voice(r["voice"])[0], r["text"], lagrange=lag,
                sim_min=args.sim_min, wer_max=args.wer_max, device=args.device,
                det_scores=det[str(r[key])],
            )
            r[f"{arm}_reward"] = rw
            r[f"{arm}_softmin"] = info["detect_reward_softmin"]
            r[f"{arm}_sim"] = info["similarity"]
            r[f"{arm}_wer"] = info["wer"]
            r[f"{arm}_det"] = info["detector_scores"]
        if not args.keep_wavs:
            Path(r["base_wav"]).unlink(missing_ok=True)
            Path(r["pol_wav"]).unlink(missing_ok=True)

    names = list(det[str(rows[0]["base_wav"])].keys())

    print("\n" + "=" * 74)
    print(f"{'pair':<5}{'voice':<9}{'softmin base':>13}{'policy':>9}{'diff':>9}"
          f"{'sim d':>8}{'wer d':>8}")
    print("-" * 74)
    for r in rows:
        print(f"{r['i']:<5}{r['voice']:<9}{r['base_softmin']:>13.4f}{r['pol_softmin']:>9.4f}"
              f"{r['pol_softmin']-r['base_softmin']:>+9.4f}"
              f"{r['pol_sim']-r['base_sim']:>+8.3f}{(r['pol_wer']-r['base_wer'])*100:>+7.1f}%")

    d_soft = np.array([r["pol_softmin"] - r["base_softmin"] for r in rows])
    d_sim = np.array([r["pol_sim"] - r["base_sim"] for r in rows])
    d_wer = np.array([r["pol_wer"] - r["base_wer"] for r in rows])

    print("\n" + "=" * 74)
    print("PAIRED DIFFERENCES (policy minus baseline, same seed / same tokens)")
    print("=" * 74)
    for label, d, fmt in (("softmin (detector evasion)", d_soft, "{:+.4f}"),
                          ("similarity", d_sim, "{:+.4f}"),
                          ("WER", d_wer, "{:+.4f}")):
        m, se, t = paired_stats(d)
        verdict = ("significant" if abs(t) > 2 else "not distinguishable from zero")
        print(f"  {label:<28} mean {fmt.format(m)}  SE {se:.4f}  t = {t:+.2f}   {verdict}")

    print("\nper-detector mean change:")
    for n in names:
        db = np.array([r["pol_det"][n] - r["base_det"][n] for r in rows])
        m, se, t = paired_stats(db)
        print(f"  {n:<12} {m:+.4f}  (SE {se:.4f}, t = {t:+.2f})")

    # ---- verdict ----
    m_soft, se_soft, t_soft = paired_stats(d_soft)
    m_sim, _, _ = paired_stats(d_sim)
    m_wer, _, _ = paired_stats(d_wer)
    sim_ok = float(np.mean([r["pol_sim"] for r in rows])) >= args.sim_min
    wer_ok = float(np.mean([r["pol_wer"] for r in rows])) <= args.wer_max

    print("\n" + "=" * 74)
    if t_soft > 2 and sim_ok and wer_ok:
        print(f"VERDICT: the policy genuinely improves evasion ({m_soft:+.4f}) and the")
        print("         constraints still hold. This is a real effect.")
    elif t_soft > 2:
        print(f"VERDICT: evasion improved ({m_soft:+.4f}) but a constraint broke")
        print(f"         (sim {'ok' if sim_ok else 'FAILED'}, wer {'ok' if wer_ok else 'FAILED'}).")
        print("         Reward hacking, not progress.")
    elif abs(t_soft) <= 2:
        print("VERDICT: the policy is not distinguishable from no policy at all.")
        print("         Whatever the training reward did, the learned mean edit")
        print("         does not beat the baseline on matched inputs.")
    else:
        print(f"VERDICT: the policy is WORSE than baseline ({m_soft:+.4f}).")
    print("=" * 74)

    out = run_dir / f"eval_{args.checkpoint.replace('.pt','')}.json"
    out.write_text(json.dumps({
        "checkpoint": str(ckpt_path), "pairs": args.pairs, "seed": args.seed,
        "rows": [{k: (str(v) if isinstance(v, Path) else v) for k, v in r.items()} for r in rows],
        "paired": {
            "softmin": dict(zip(("mean", "se", "t"), paired_stats(d_soft))),
            "similarity": dict(zip(("mean", "se", "t"), paired_stats(d_sim))),
            "wer": dict(zip(("mean", "se", "t"), paired_stats(d_wer))),
        },
    }, indent=2), encoding="utf8")
    print(f"\nwrote {out}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
